// models/unitree_g1/scene_mjx_stones.xml: the policy's scene (scene_mjx.xml) with a field of low
// stones on the floor, for the "piedras" world (physics/worlds/piedras.json). The robot, its
// motors and every contact stay the same; the stones are a height field over the flat floor, with
// the feet's contact pairs repeated against it. Run again if scene_mjx.xml changes:
// npm run make-stones-scene (check-worlds loads the file, so a broken one fails the checks).
import { readFileSync, writeFileSync } from 'node:fs';

const DIR = new URL('../models/unitree_g1/', import.meta.url);
// Stones up to 3 cm: enough to make a foot land tilted, low enough that the pelvis height of a
// clip retargeted on flat ground still holds (docs/plan-producto.md, SIM-3).
const STONE_MAX_M = 0.03;
// The field covers 8 x 8 m around the start, in 5 cm cells: a stone of 10 cm spans a few cells.
const HALF_SIZE_M = 4;
const CELL_M = 0.05;
const STONES = 900; // about 14 per square meter: a foot lands on one most steps
const STONE_RADIUS_M = [0.04, 0.12];
// A clear square around the start, so the robot is placed on flat ground and the first frames
// look like the flat world's.
const CLEAR_M = 0.6;
const SEED = 26; // fixed: the same stones in the browser and in training, every time

// mulberry32: a small seeded generator, so the terrain is the same on every run.
function random(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const n = Math.round((2 * HALF_SIZE_M) / CELL_M) + 1;
const height = new Float32Array(n * n);
const rand = random(SEED);
for (let s = 0; s < STONES; s++) {
  const cx = (rand() * 2 - 1) * HALF_SIZE_M;
  const cy = (rand() * 2 - 1) * HALF_SIZE_M;
  if (Math.abs(cx) < CLEAR_M && Math.abs(cy) < CLEAR_M) continue;
  const r = STONE_RADIUS_M[0] + rand() * (STONE_RADIUS_M[1] - STONE_RADIUS_M[0]);
  const h = STONE_MAX_M * (0.4 + 0.6 * rand());
  // A rounded stone: a smooth dome, highest at its center.
  const span = Math.ceil(r / CELL_M);
  const ci = Math.round((cx + HALF_SIZE_M) / CELL_M);
  const cj = Math.round((cy + HALF_SIZE_M) / CELL_M);
  for (let i = Math.max(0, ci - span); i <= Math.min(n - 1, ci + span); i++) {
    for (let j = Math.max(0, cj - span); j <= Math.min(n - 1, cj + span); j++) {
      const d = Math.hypot(i * CELL_M - HALF_SIZE_M - cx, j * CELL_M - HALF_SIZE_M - cy) / r;
      if (d < 1) height[j * n + i] = Math.max(height[j * n + i], h * Math.cos((d * Math.PI) / 2) ** 2);
    }
  }
}

// MuJoCo takes elevations from 0 to 1, scaled by the third size value (the stone height).
const elevation = Array.from(height, (z) => (z / STONE_MAX_M).toFixed(3).replace(/^0\./, '.').replace(/^\.000$/, '0'));
const rows = [];
for (let j = 0; j < n; j++) rows.push(elevation.slice(j * n, (j + 1) * n).join(' '));

const FEET = ['left_foot1', 'left_foot2', 'left_foot3', 'right_foot1', 'right_foot2', 'right_foot3'];
const source = readFileSync(new URL('scene_mjx.xml', DIR), 'utf8');
let scene = source
  .replace('<mujoco model="g1 mjx flat terrain scene">', '<mujoco model="g1 mjx stones scene">\n  <!-- Generated by physics/scripts/make-stones-scene.mjs from scene_mjx.xml: low stones on the floor. -->')
  .replace(
    '  </asset>',
    `    <material name="stones" rgba="0.62 0.66 0.72 1"/>\n` +
      `    <!-- ${n} x ${n} cells of ${CELL_M * 100} cm over ${2 * HALF_SIZE_M} x ${2 * HALF_SIZE_M} m; stones up to ${STONE_MAX_M * 100} cm. -->\n` +
      `    <hfield name="stones" nrow="${n}" ncol="${n}" size="${HALF_SIZE_M} ${HALF_SIZE_M} ${STONE_MAX_M} 0.01"\n      elevation="${rows.join('\n        ')}"/>\n  </asset>`,
  )
  .replace(
    '    <geom name="floor" size="0 0 0.01" type="plane" material="groundplane"/>',
    '    <geom name="floor" size="0 0 0.01" type="plane" material="groundplane"/>\n    <geom name="stones" type="hfield" hfield="stones" material="stones"/>',
  )
  .replace(
    '    <!-- foot - foot -->',
    FEET.map((f) => `    <pair name="${f}_stones" geom1="${f}_collision" geom2="stones" solref="0.008 1" friction="1 1" condim="3"/>`).join('\n') +
      '\n    <!-- foot - foot -->',
  );
for (const marker of ['<hfield name="stones"', 'type="hfield"', 'right_foot3_stones']) {
  if (!scene.includes(marker)) throw new Error(`scene_mjx.xml changed: could not add ${marker}`);
}
writeFileSync(new URL('scene_mjx_stones.xml', DIR), scene);
console.log(`scene_mjx_stones.xml: ${n} x ${n} height field, ${(scene.length / 1024).toFixed(0)} KB`);
