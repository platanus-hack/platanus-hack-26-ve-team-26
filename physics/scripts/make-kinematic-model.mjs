// models/unitree_g1/g1_kinematics.xml: g1.xml without its meshes. The retargeting only needs the
// kinematic chain and the spheres under the feet, and loading the 35 meshes takes about 3 s in a
// browser. Run again if g1.xml changes: npm run make-kinematic-model (check-retarget compares the
// two models, so a stale file fails the checks).
import { readFileSync, writeFileSync } from 'node:fs';

const DIR = new URL('../models/unitree_g1/', import.meta.url);
const source = readFileSync(new URL('g1.xml', DIR), 'utf8');
const stripped = source
  .replace(/^[ \t]*<mesh [^>]*\/>[ \t]*\n/gm, '') // the mesh assets
  .replace(/^[ \t]*<geom [^>]*\bmesh="[^"]*"[^>]*\/>[ \t]*\n/gm, '') // the geoms drawn or colliding with them
  .replace('<mujoco model="g1_29dof_rev_1_0">', '<mujoco model="g1_29dof_rev_1_0 kinematics">\n  <!-- Generated by physics/scripts/make-kinematic-model.mjs from g1.xml: no meshes. -->');
writeFileSync(new URL('g1_kinematics.xml', DIR), stripped);
console.log(`g1_kinematics.xml: ${source.length} -> ${stripped.length} bytes`);
